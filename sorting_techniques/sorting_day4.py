# SORTING  Techniques
# Sorting means arranging the elements of an array or list in a particular order.

# We can arrange elements in:
# 1. Ascending order  → Small to large
# 2. Descending order → Large to small


# WHY DO WE USE SORTING?
# - Sorting makes data organized.
# - It makes searching easier and faster.
# - It helps in finding minimum and maximum elements.
# - It helps in solving many DSA problems.
# - It makes duplicate elements easier to find.


# COMMON SORTING ALGORITHMS
# 1. Bubble Sort
# 2. Selection Sort
# 3. Insertion Sort
# 4. Merge Sort
# 5. Quick Sort
# 6. Heap Sort


# Bubble Sort:
# It compares adjacent elements and swaps them
# if they are in the wrong order.

# Selection Sort:
# It finds the smallest element and places it
# in the correct position.

# Insertion Sort:
# It takes one element at a time and inserts it
# into its correct position.

# Merge Sort:
# It divides the array into smaller parts,
# sorts them and then merges them.

# Quick Sort:
# It selects a pivot and divides the array
# based on the pivot.

# Heap Sort:
# It uses a heap data structure to sort the elements.


# TIME COMPLEXITY
# Bubble Sort     → O(n²)
# Selection Sort  → O(n²)
# Insertion Sort  → O(n²)
# Merge Sort      → O(n log n)
# Quick Sort      → O(n log n) average
# Heap Sort       → O(n log n)

# SPACE COMPLEXITY
# Bubble Sort     → O(1)
# Selection Sort  → O(1)
# Insertion Sort  → O(1)
# Merge Sort      → O(n)
# Quick Sort      → O(log n) average
# Heap Sort       → O(1)

# IMPORTANT:
# Sorting is useful because many algorithms,such as Binary Search, work efficiently on sorted data.