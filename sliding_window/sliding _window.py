#Sliding Window is an algorithmic technique used to solve problems involving continuous elements in an array or string.

# In simple words:
# - We select a group of consecutive elements.
# - That group is called a window.
# - We perform an operation on those elements.
# - We move the window forward to process the next group.
# Instead of calculating everything repeatedly, we reuse the previous window's result


#There are two main Sliding Window algorithms:
# 1. Fixed-size Sliding Window
# 2. Variable-size Sliding Window